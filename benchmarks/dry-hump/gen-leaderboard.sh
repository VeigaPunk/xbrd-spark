#!/usr/bin/env bash
# Rebuild LEADERBOARD.md from telemetry-12x/runs/*/summary.json (bash + jq only).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
TELE=${1:-"$HERE/telemetry-12x"}
OUT="$TELE/LEADERBOARD.md"
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

: > "$TMP"
for p in "$TELE"/runs/*/summary.json; do
  [[ -f "$p" ]] || continue
  jq -r '[
    .run_id,
    .model_label,
    (.wall_seconds|tostring),
    (.sparks_ok|tostring),
    (.sparks_fail|tostring),
    (.sparks_timeout|tostring),
    ((.tokens_total // 0)|tostring)
  ] | @tsv' "$p" >> "$TMP"
done

{
  echo "# dry-hump multi-model leaderboard"
  echo
  echo "Generated by \`gen-leaderboard.sh\` from \`summary.json\` only (no live API)."
  echo "Shape: **8 domains × 8 sparks = 64 concurrent** via \`sekhmet swarm -j 8\`."
  echo
  echo "## Complete runs (64 ok / 0 fail / 0 timeout)"
  echo
  echo "| rank | run_id | model | wall s | ok | fail | timeout | sekhmet tokens |"
  echo "|-----:|--------|-------|-------:|---:|-----:|--------:|---------------:|"
  awk -F'\t' '$4=="64" && $5=="0" && $6=="0"' "$TMP" \
    | sort -t$'\t' -k3,3n \
    | awk -F'\t' '{
        printf "| %d | `%s` | `%s` | %s | %s | %s | %s | %s |\n", NR, $1, $2, $3, $4, $5, $6, $7
      }'
  echo
  echo "## Incomplete / failed harvests"
  echo
  echo "| run_id | model | wall s | ok | fail | timeout | sekhmet tokens |"
  echo "|--------|-------|-------:|---:|-----:|--------:|---------------:|"
  awk -F'\t' '!( $4=="64" && $5=="0" && $6=="0" )' "$TMP" \
    | sort -t$'\t' -k1,1 \
    | awk -F'\t' '{
        printf "| `%s` | `%s` | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6, $7
      }'
  echo
  echo "## Notes"
  echo
  echo "- Wall seconds are sekhmet pool wall (domain barrier end), not opencode agent wall."
  echo "- \`tokens_total\` parsed from Titanium \`result.json\` when present; 0 means parse miss or empty harvest."
  echo "- Near-zero wall + 0 ok usually means the outer agent failed to invoke sekhmet (tmpfs quota or tool skip)."
  echo "- Live \`/tmp/sekhmet-12x-*\` roots must be deleted after harvest; see \`run-once-telemetry.sh\` EXIT trap."
  echo
  echo "_Regenerate: \`./benchmarks/dry-hump/gen-leaderboard.sh\`_"
} > "$OUT"

echo "wrote $OUT"
